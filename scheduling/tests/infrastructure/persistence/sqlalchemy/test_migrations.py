"""Verify metadata is isolated and Alembic can inspect scheduling tables."""

from alembic.autogenerate.api import AutogenContext
from alembic.migration import MigrationContext
from sqlalchemy import Integer, MetaData, Table

from scheduling.infrastructure.persistence.sqlalchemy import (
    is_scheduling_table,
    render_scheduling_type,
    scheduling_metadata,
)


def test_host_can_combine_metadata_without_package_specific_engine() -> None:
    host = MetaData()
    Table("host_accounts", host)
    package = scheduling_metadata()

    assert "scheduling_calendars" in package.tables
    assert "host_accounts" in host.tables
    assert is_scheduling_table("scheduling_calendars", "table")
    assert not is_scheduling_table("host_accounts", "table")
    assert not is_scheduling_table(None, "table")
    assert not is_scheduling_table("scheduling_calendars", "column")


def test_autogenerated_jsonb_variant_has_no_unqualified_type_reference() -> None:
    context = AutogenContext(MigrationContext.configure(dialect_name="postgresql"))
    column = scheduling_metadata().tables["scheduling_calendars"].c.weekly_schedule

    rendered = render_scheduling_type("type", column.type, context)

    assert rendered == "sa.JSON().with_variant(postgresql.JSONB(), 'postgresql')"
    assert "from sqlalchemy.dialects import postgresql" in context.imports
    assert render_scheduling_type("type", Integer(), context) is False
    assert render_scheduling_type("column", column.type, context) is False
